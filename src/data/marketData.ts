// Technical Candle generator for accurate OHLCV across timeframes
export function generateCandlesForSymbol(symbol: string, timeframe: string, currentPrice: number): CandleData[] {
  let count = 40;
  let intervalMins = 5;

  if (timeframe === '1D') {
    count = 48;
    intervalMins = 5;
  } else if (timeframe === '5D') {
    count = 60;
    intervalMins = 30;
  } else if (timeframe === '1M') {
    count = 30;
    intervalMins = 1440; // 1 day
  } else if (timeframe === '6M') {
    count = 50;
    intervalMins = 1440 * 3;
  } else if (timeframe === 'YTD' || timeframe === '1Y') {
    count = 60;
    intervalMins = 1440 * 5;
  } else {
    count = 70;
    intervalMins = 1440 * 14;
  }

  const candles: CandleData[] = [];
  const now = Date.now();
  let basePrice = currentPrice * 0.94; // start slightly below

  // Pseudo-random walk with seed based on symbol name
  const seed = symbol.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);

  for (let i = 0; i < count; i++) {
    const timeOffset = (count - i) * intervalMins * 60 * 1000;
    const time = now - timeOffset;
    const dateObj = new Date(time);

    let dateStr = '';
    if (timeframe === '1D' || timeframe === '5D') {
      dateStr = dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    } else {
      dateStr = dateObj.toLocaleDateString([], { month: 'short', day: 'numeric' });
    }

    const pseudoRandom = Math.sin(seed + i * 1.7) * 0.5 + Math.cos(seed * 0.5 + i * 2.3) * 0.5;
    const volatility = currentPrice * 0.012;
    const change = pseudoRandom * volatility;

    // Drifting towards currentPrice as i approaches count - 1
    const progress = i / count;
    const targetPrice = currentPrice * 0.92 + (currentPrice * 0.08 * progress);
    basePrice = basePrice * 0.7 + targetPrice * 0.3 + change;

    const open = i === 0 ? basePrice : candles[i - 1].close;
    const high = Math.max(open, basePrice) + Math.abs(pseudoRandom) * (volatility * 0.6);
    const low = Math.min(open, basePrice) - Math.abs(pseudoRandom) * (volatility * 0.5);
    const close = i === count - 1 ? currentPrice : basePrice;
    const volume = Math.floor(10000 + Math.abs(pseudoRandom * 80000));

    candles.push({
      timestamp: time,
      dateStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  return candles;
}
